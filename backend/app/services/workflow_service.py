"""Workflow orchestration service.

Composes the deterministic state machine with application handlers and the AI
components. Workflows are built from the approved knowledge templates (required
documents, deterministic rules, state diagrams), not generated by an LLM. The AI
provider is strictly an *advisory* layer: it can flag warnings that prompt a
human review, but it can never reverse a deterministic block.
"""

